-- Funções de verificação de regularidade do consórcio
CREATE OR REPLACE FUNCTION public.check_consortium_regularity_by_participant(p_participant_id uuid)
RETURNS TABLE (
    is_regular boolean,
    status_text text
) AS $$
DECLARE
    v_participant RECORD;
    v_current_day integer;
    v_current_month_start timestamp with time zone;
    v_order_exists boolean;
BEGIN
    SELECT user_id, customer_email, customer_cpf INTO v_participant 
    FROM public.consortium_participants 
    WHERE id = p_participant_id;
    
    IF v_participant.customer_email IS NULL THEN
        is_regular := true;
        status_text := 'Ativo';
        RETURN NEXT;
        RETURN;
    END IF;

    v_current_month_start := date_trunc('month', now());
    v_current_day := extract(day from now());

    SELECT EXISTS (
        SELECT 1 
        FROM public.orders o
        JOIN public.order_items oi ON o.id = oi.order_id
        WHERE o.customer_email = v_participant.customer_email
        AND o.status = 'Pago'
        AND o.created_at >= v_current_month_start
        AND (oi.product_name ILIKE '%Consórcio%' OR oi.product_name ILIKE '%Concorcio%')
    ) INTO v_order_exists;

    is_regular := v_order_exists;
    IF v_order_exists THEN
        status_text := 'Regular';
    ELSE
        IF v_current_day > 10 THEN
            status_text := 'Irregular';
        ELSE
            status_text := 'Pendente';
        END IF;
    END IF;
    
    RETURN NEXT;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE OR REPLACE FUNCTION public.get_consortium_by_cpf(p_cpf text)
RETURNS json AS $$
DECLARE
    v_participant RECORD;
    v_draws json;
    v_regularity json;
    v_result json;
BEGIN
    SELECT 
        p.id as participant_id,
        p.group_id,
        p.lucky_number,
        p.status as participant_status,
        p.customer_name,
        g.name as group_name,
        g.type as group_type,
        g.current_participants,
        g.max_participants,
        g.status as group_status,
        g.product_id
    INTO v_participant
    FROM public.consortium_participants p
    JOIN public.consortium_groups g ON p.group_id = g.id
    WHERE regexp_replace(p.customer_cpf, '\D', '', 'g') = regexp_replace(p_cpf, '\D', '', 'g')
    ORDER BY p.joined_at DESC
    LIMIT 1;

    IF v_participant.participant_id IS NULL THEN
        RETURN NULL;
    END IF;

    SELECT json_agg(d_list) INTO v_draws
    FROM (
        SELECT 
            d.*,
            (
                SELECT lucky_number 
                FROM public.consortium_participants 
                WHERE id = d.winner_id
            ) as winner_lucky_number
        FROM public.consortium_draws d
        WHERE d.group_id = v_participant.group_id
        ORDER BY d.draw_date DESC
    ) d_list;

    BEGIN
        SELECT json_build_object(
            'is_regular', r.is_regular,
            'status_text', r.status_text
        ) INTO v_regularity
        FROM public.check_consortium_regularity_by_participant(v_participant.participant_id) r;
    EXCEPTION WHEN OTHERS THEN
        v_regularity := json_build_object('is_regular', true, 'status_text', 'Ativo');
    END;

    v_result := json_build_object(
        'participant', json_build_object(
            'name', v_participant.customer_name,
            'lucky_number', v_participant.lucky_number,
            'status', v_participant.participant_status,
            'regularity', v_regularity
        ),
        'group', json_build_object(
            'name', v_participant.group_name,
            'type', v_participant.group_type,
            'current', v_participant.current_participants,
            'max', v_participant.max_participants,
            'status', v_participant.group_status
        ),
        'draws', COALESCE(v_draws, '[]'::json)
    );

    RETURN v_result;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE OR REPLACE FUNCTION public.get_upline_chain(p_user_id uuid, max_depth integer)
RETURNS TABLE (
    level integer,
    user_id uuid,
    email text,
    full_name text,
    sponsor_id uuid
) AS $$
BEGIN
    RETURN QUERY
    WITH RECURSIVE upline_tree AS (
        SELECT 
            1 as lvl,
            sp.user_id as u_id,
            sp.email as u_email,
            sp.full_name as u_name,
            sp.sponsor_id as u_sponsor_id
        FROM public.affiliates a
        JOIN public.affiliates sp ON a.sponsor_id = sp.id
        WHERE a.user_id = p_user_id
        
        UNION ALL
        
        SELECT 
            ut.lvl + 1,
            sp.user_id,
            sp.email,
            sp.full_name,
            sp.sponsor_id
        FROM public.affiliates sp
        JOIN upline_tree ut ON ut.u_sponsor_id = sp.id
        WHERE ut.lvl < max_depth
    )
    SELECT 
        ut.lvl,
        ut.u_id,
        ut.u_email,
        ut.u_name,
        ut.u_sponsor_id
    FROM upline_tree ut;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

