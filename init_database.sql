-- Distribuição de Comissões Multinível
CREATE OR REPLACE FUNCTION public.distribute_commissions()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_affiliate RECORD;
    v_current_sponsor_id uuid;
    v_config RECORD;
    v_commission_amount numeric;
    v_gen_count integer := 0;
    v_active_gens integer;
    v_target_user_id uuid;
    v_is_master boolean := false;
    v_config_key text;
BEGIN
    -- Só processa se o status mudar para 'Pago'
    IF (OLD.status IS NULL OR OLD.status != 'Pago') AND NEW.status = 'Pago' THEN
        
        -- Evita processamento duplicado
        IF EXISTS (SELECT 1 FROM public.commissions WHERE order_id = NEW.id) THEN
            RETURN NEW;
        END IF;

        -- Identificar tipo de comissão
        SELECT EXISTS (
            SELECT 1 FROM public.order_items oi
            JOIN public.products p ON oi.product_id = p.id
            LEFT JOIN public.product_categories pc ON p.category_id = pc.id
            WHERE oi.order_id = NEW.id
            AND (p.name ILIKE '%Colchão%' OR pc.name ILIKE '%Colchão%')
        ) INTO v_is_master;

        v_config_key := CASE WHEN v_is_master THEN 'mattress' ELSE 'geral' END;

        -- Buscar Configurações
        SELECT * INTO v_config FROM public.commission_configs WHERE key = v_config_key;
        
        IF v_config IS NULL THEN
            SELECT * INTO v_config FROM public.commission_configs WHERE key = 'geral';
        END IF;

        IF v_config IS NULL THEN
            RETURN NEW;
        END IF;

        v_active_gens := v_config.active_generations;

        -- Prioridade 1: Código de referência no pedido
        IF NEW.referral_code IS NOT NULL AND NEW.referral_code != '' THEN
            SELECT * INTO v_affiliate FROM public.affiliates 
            WHERE LOWER(referral_code) = LOWER(NEW.referral_code) 
            AND organization_id = NEW.organization_id
            AND (
                NEW.organization_id != '5111af72-27a5-41fd-8ed9-8c51b78b4fdd'
                OR user_id != NEW.user_id
            )
            LIMIT 1;
        END IF;

        -- Prioridade 2: Patrocinador do comprador
        IF v_affiliate IS NULL AND NEW.user_id IS NOT NULL THEN
            SELECT a.* INTO v_affiliate 
            FROM public.affiliates a
            JOIN public.user_profiles p ON p.sponsor_id = a.user_id
            WHERE p.id = NEW.user_id 
            AND a.organization_id = NEW.organization_id
            AND (
                NEW.organization_id != '5111af72-27a5-41fd-8ed9-8c51b78b4fdd'
                OR a.user_id != NEW.user_id
            )
            LIMIT 1;
        END IF;

        IF v_affiliate IS NULL THEN
            RETURN NEW;
        END IF;

        v_current_sponsor_id := v_affiliate.id;

        -- Distribuir pelos Níveis
        WHILE v_gen_count < v_active_gens AND v_current_sponsor_id IS NOT NULL LOOP
            v_gen_count := v_gen_count + 1;
            
            SELECT (lvl->>'value')::numeric INTO v_commission_amount
            FROM jsonb_array_elements(v_config.levels) AS lvl
            WHERE (lvl->>'level')::integer = v_gen_count;

            IF v_commission_amount IS NOT NULL AND v_commission_amount > 0 THEN
                IF v_config.type = 'percent' THEN
                    v_commission_amount := NEW.total_amount * (v_commission_amount / 100);
                END IF;

                SELECT user_id INTO v_target_user_id FROM public.affiliates WHERE id = v_current_sponsor_id;

                IF v_target_user_id IS NOT NULL THEN
                    UPDATE public.user_settings 
                    SET 
                        total_earnings = total_earnings + v_commission_amount,
                        available_balance = available_balance + v_commission_amount,
                        updated_at = now()
                    WHERE user_id = v_target_user_id;

                    INSERT INTO public.commissions (
                        organization_id,
                        user_id,
                        order_id,
                        amount,
                        level,
                        commission_type,
                        description
                    ) VALUES (
                        NEW.organization_id,
                        v_target_user_id,
                        NEW.id,
                        v_commission_amount,
                        v_gen_count,
                        v_config.type,
                        'Comissão ' || v_config_key || ' Geração ' || v_gen_count || ' - Pedido ' || NEW.id
                    );
                END IF;
            END IF;

            SELECT sponsor_id INTO v_current_sponsor_id 
            FROM public.affiliates 
            WHERE id = v_current_sponsor_id 
            AND organization_id = NEW.organization_id;
            
            IF v_gen_count > 50 THEN EXIT; END IF;
        END LOOP;
    END IF;

    RETURN NEW;
END;
$$;

-- Automação de Alocação de Grupos de Consórcio
CREATE OR REPLACE FUNCTION public.handle_consortium_purchase()
RETURNS trigger AS $$
DECLARE
    v_item RECORD;
    v_group_id uuid;
    v_max_p integer;
    v_group_type text;
    v_lucky_number integer;
    v_group_name text;
BEGIN
    IF (OLD.status IS NULL OR OLD.status != 'Pago') AND NEW.status = 'Pago' THEN
        
        FOR v_item IN 
            SELECT oi.*, p.name as p_name, pc.name as cat_name
            FROM public.order_items oi
            JOIN public.products p ON oi.product_id = p.id
            LEFT JOIN public.product_categories pc ON p.category_id = pc.id
            WHERE oi.order_id = NEW.id
            AND (pc.name ILIKE '%Consórcio%' OR p.name ILIKE '%Consórcio%')
        LOOP
            IF v_item.p_name ILIKE '%Colchão%' OR v_item.cat_name ILIKE '%Colchão%' THEN
                v_max_p := 18;
                v_group_type := 'colchao';
            ELSE
                v_max_p := 12;
                v_group_type := 'livre_escolha';
            END IF;

            SELECT g.id INTO v_group_id
            FROM public.consortium_groups g
            WHERE g.status = 'open'
            AND g.product_id = v_item.product_id
            AND g.organization_id = NEW.organization_id
            AND g.current_participants < v_max_p
            ORDER BY g.created_at ASC
            LIMIT 1;

            IF v_group_id IS NULL THEN
                v_group_name := 'Grupo ' || v_item.p_name || ' #' || 
                    (SELECT count(*) + 1 FROM public.consortium_groups WHERE product_id = v_item.product_id);

                INSERT INTO public.consortium_groups (
                    name,
                    type,
                    max_participants,
                    product_id,
                    organization_id,
                    status,
                    current_participants
                ) VALUES (
                    v_group_name,
                    v_group_type,
                    v_max_p,
                    v_item.product_id,
                    NEW.organization_id,
                    'open',
                    0
                ) RETURNING id INTO v_group_id;
            END IF;

            SELECT next_num INTO v_lucky_number
            FROM generate_series(1, v_max_p) next_num
            WHERE next_num NOT IN (
                SELECT lucky_number FROM public.consortium_participants WHERE group_id = v_group_id
            )
            ORDER BY next_num ASC
            LIMIT 1;

            IF v_lucky_number IS NOT NULL THEN
                INSERT INTO public.consortium_participants (
                    group_id,
                    user_id,
                    customer_name,
                    customer_cpf,
                    customer_email,
                    lucky_number,
                    status
                ) VALUES (
                    v_group_id,
                    NEW.user_id,
                    NEW.customer_name,
                    NEW.customer_cpf,
                    NEW.customer_email,
                    v_lucky_number,
                    'active'
                );

                UPDATE public.consortium_groups
                SET current_participants = (
                    SELECT count(*) FROM public.consortium_participants WHERE group_id = v_group_id
                )
                WHERE id = v_group_id;

                UPDATE public.consortium_groups
                SET status = 'full'
                WHERE id = v_group_id AND current_participants >= max_participants;
            END IF;

        END LOOP;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Funções Administrativas (RPC)
CREATE OR REPLACE FUNCTION public.admin_update_user_auth(
    p_user_id uuid,
    p_email text,
    p_password text
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM public.user_profiles
        WHERE id = auth.uid() AND role = 'admin'
    ) THEN
        RAISE EXCEPTION 'Apenas administradores podem atualizar credenciais de usuários.';
    END IF;

    IF p_password IS NOT NULL AND p_password <> '' THEN
        UPDATE auth.users
        SET email = COALESCE(p_email, email),
            encrypted_password = crypt(p_password, gen_salt('bf')),
            email_confirmed_at = CASE WHEN p_email IS NOT NULL THEN now() ELSE email_confirmed_at END,
            updated_at = now()
        WHERE id = p_user_id;
    ELSE
        UPDATE auth.users
        SET email = COALESCE(p_email, email),
            email_confirmed_at = CASE WHEN p_email IS NOT NULL THEN now() ELSE email_confirmed_at END,
            updated_at = now()
        WHERE id = p_user_id;
    END IF;

    IF p_email IS NOT NULL THEN
        UPDATE public.user_profiles SET email = p_email WHERE id = p_user_id;
        UPDATE public.affiliates SET email = p_email WHERE user_id = p_user_id;
    END IF;
END;
$$;

