-- Função para verificar se o usuário autenticado é Admin
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS boolean AS $$
BEGIN
  RETURN EXISTS (
    SELECT 1 FROM public.user_profiles
    WHERE id = auth.uid() AND role = 'admin'
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

-- Função genérica para atualizar updated_at
CREATE OR REPLACE FUNCTION public.update_updated_at_column()
RETURNS trigger AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Trigger para sincronizar organization_id no app_metadata do usuário auth
CREATE OR REPLACE FUNCTION public.handle_auth_user_app_metadata()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE 
    v_org_id uuid;
BEGIN
  BEGIN
    v_org_id := NULLIF(new.raw_user_meta_data ->> 'organization_id', '')::uuid;
  EXCEPTION WHEN OTHERS THEN
    v_org_id := NULL;
  END;
  
  IF v_org_id IS NULL THEN
     SELECT id INTO v_org_id FROM public.organizations WHERE name = 'Classe A' LIMIT 1;
  END IF;
  
  IF v_org_id IS NULL THEN
     v_org_id := '5111af72-27a5-41fd-8ed9-8c51b78b4fdd'::uuid;
  END IF;

  new.raw_app_meta_data := coalesce(new.raw_app_meta_data, '{}'::jsonb) || jsonb_build_object('organization_id', v_org_id);
  
  RETURN new;
END;
$function$;

